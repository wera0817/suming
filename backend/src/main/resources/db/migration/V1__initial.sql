CREATE TABLE app_state (name VARCHAR(80) PRIMARY KEY, value MEDIUMTEXT NOT NULL);
CREATE TABLE admin_sessions (token CHAR(64) PRIMARY KEY, expires_at TIMESTAMP NOT NULL);
CREATE TABLE knowledge (
  id VARCHAR(64) PRIMARY KEY, title VARCHAR(200) NOT NULL, body TEXT NOT NULL,
  category VARCHAR(20) NOT NULL, school VARCHAR(100) NOT NULL, source VARCHAR(500) NOT NULL,
  edition VARCHAR(200) NOT NULL, rights VARCHAR(500) NOT NULL,
  verified BOOLEAN NOT NULL DEFAULT FALSE, enabled BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE reports (
  id CHAR(36) PRIMARY KEY, owner CHAR(64) NOT NULL, kind VARCHAR(12) NOT NULL,
  question VARCHAR(2000) NOT NULL, background VARCHAR(4000) NOT NULL,
  chart JSON NULL, observation TEXT NULL, sources JSON NOT NULL,
  status VARCHAR(20) NOT NULL, error_code VARCHAR(40) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX owner_created(owner, created_at)
);
CREATE TABLE messages (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, report_id CHAR(36) NOT NULL,
  role VARCHAR(12) NOT NULL, content MEDIUMTEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(report_id) REFERENCES reports(id) ON DELETE CASCADE
);
CREATE TABLE run_logs (
  id CHAR(36) PRIMARY KEY, operation VARCHAR(24) NOT NULL, status VARCHAR(40) NOT NULL,
  duration_ms BIGINT NOT NULL, total_tokens INT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
